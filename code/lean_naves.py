"""Writes lean/Spaceships.lean from data/spaceships/c5.rle: the c/5 spaceship as an explicit
board, with its period, displacement, border clearance and phase populations stated for
the Lean kernel to check by `decide`.

The populations written into the Lean file are computed here, by code/naves.py; Lean then
recomputes them independently, so a wrong number fails the build.

Run: python lean_naves.py   (CI regenerates the file and checks it has not changed)
"""
import os

import naves as N

AQUI = os.path.dirname(os.path.abspath(__file__))
RAIZ = os.path.dirname(AQUI)
MARGEN = 3


def tablero():
    _, g = N.lee_rle(os.path.join(N.NAVES, "c5.rle"))
    h, w = g.shape
    # una fila mas arriba: la nave sube una fila por periodo
    filas = [[0] * (w + 2 * MARGEN) for _ in range(h + 2 * MARGEN + 1)]
    for y in range(h):
        for x in range(w):
            filas[y + MARGEN + 1][x + MARGEN] = int(g[y, x])
    return filas


def poblaciones(filas):
    import numpy as np
    g = np.array(filas, np.uint8)
    out = []
    for _ in range(5):
        out.append(int(g.sum()))
        n = N.vecinas(g)
        g = np.where(g == 1, np.isin(n, (2, 3, 7, 8)), np.isin(n, (3, 7))).astype(np.uint8)
    return out


def lean(filas, pob):
    alto, ancho = len(filas), len(filas[0])
    cuerpo = ",\n".join("   \"" + "".join("o" if c else "." for c in f) + "\"" for f in filas)
    return f'''/-!
# A c/5 spaceship of B37/S2378

Generated by `code/lean_naves.py` from `data/spaceships/c5.rle`; do not edit by hand.

Core Lean only, no imports. The ship (177 cells, 15 × 40) sits on a {ancho} × {alto} board with a
margin of at least {MARGEN} cells on every side. Every statement is a finite evaluation closed by
`decide` in the kernel (no `native_decide`):

* `c5_moves`: five generations of `B37/S2378` give the same board moved up by one row;
* `c5_clear`: in each of those generations the outermost rows and columns are dead. A cell
  outside the board then has at most the dead border as neighbours, so nothing is born
  outside it and the board evolves exactly as the pattern does on the infinite plane;
* `c5_populations`: the five phases have {", ".join(map(str, pob))} live cells. A translate
  keeps the number of cells, so no phase before the fifth is a translate of the first and the
  period is exactly 5;
* `c5_not_conway`: under Conway's `B3/S23` five generations do not move it by one row.
-/

namespace Spaceships

/-- A board: a list of rows; `true` is alive. Outside the list everything is dead. -/
abbrev Board := List (List Bool)

/-- The cell at `(y, x)`; out of range it is dead. -/
def get (b : Board) (y x : Nat) : Bool := (b.getD y []).getD x false

/-- Live cells among the eight neighbours of `(y, x)`; cells at negative coordinates are dead. -/
def neighbours (b : Board) (y x : Nat) : Nat :=
  let c (dy dx : Int) : Nat :=
    let yy : Int := (y : Int) + dy
    let xx : Int := (x : Int) + dx
    if 0 ≤ yy ∧ 0 ≤ xx then (if get b yy.toNat xx.toNat then 1 else 0) else 0
  c (-1) (-1) + c (-1) 0 + c (-1) 1 + c 0 (-1) + c 0 1 + c 1 (-1) + c 1 0 + c 1 1

/-- One generation of the rule with birth set `birth` and survival set `survive`. -/
def step (birth survive : List Nat) (b : Board) : Board :=
  (List.range b.length).map fun y =>
    (List.range ((b.getD 0 []).length)).map fun x =>
      let n := neighbours b y x
      if get b y x then survive.contains n else birth.contains n

/-- `B37/S2378`: born with 3 or 7 live neighbours, survives with 2, 3, 7 or 8. -/
def houseStep : Board → Board := step [3, 7] [2, 3, 7, 8]

/-- Conway's `B3/S23`. -/
def conwayStep : Board → Board := step [3] [2, 3]

/-- `n` generations. -/
def iter (f : Board → Board) : Nat → Board → Board
  | 0, b => b
  | n + 1, b => iter f n (f b)

/-- The board moved up by one row: drop the top row, add a dead one at the bottom. -/
def up (b : Board) : Board := b.tail ++ [List.replicate ((b.getD 0 []).length) false]

/-- Outermost rows and columns all dead. -/
def clear (b : Board) : Bool :=
  (b.headD []).all (· == false) && (b.getLastD []).all (· == false) &&
    b.all (fun r => r.headD false == false && r.getLastD false == false)

/-- Live cells on the board. -/
def population (b : Board) : Nat := (b.map fun r => (r.filter id).length).foldl (· + ·) 0

/-- A row from a string: `o` alive, `.` dead. -/
def row (s : String) : List Bool := s.toList.map (· == 'o')

/-- The c/5 spaceship, 177 cells, on a {ancho} × {alto} board. -/
def c5 : Board := List.map row [
{cuerpo}]

set_option maxRecDepth 100000
set_option maxHeartbeats 0

theorem c5_moves : iter houseStep 5 c5 = up c5 := by decide

theorem c5_clear : ∀ k ∈ [0, 1, 2, 3, 4, 5], clear (iter houseStep k c5) = true := by decide

theorem c5_populations :
    [0, 1, 2, 3, 4].map (fun k => population (iter houseStep k c5)) = [{", ".join(map(str, pob))}] := by
  decide

theorem c5_not_conway : iter conwayStep 5 c5 ≠ up c5 := by decide

end Spaceships

#print axioms Spaceships.c5_moves
#print axioms Spaceships.c5_clear
#print axioms Spaceships.c5_populations
#print axioms Spaceships.c5_not_conway
'''


if __name__ == "__main__":
    f = tablero()
    p = poblaciones(f)
    assert p == [177, 186, 194, 184, 180], p
    with open(os.path.join(RAIZ, "lean", "Spaceships.lean"), "w", encoding="utf-8", newline="\n") as h:
        h.write(lean(f, p))
    print("lean/Spaceships.lean:", len(f[0]), "x", len(f), "board, populations", p)
